def set_rtl(paragraph):
    pPr = paragraph._p.get_or_add_pPr()
    bidi = OxmlElement('w:bidi')
    pPr.append(bidi)


def style_run(run, size=12, bold=False, italic=False, color=None, font_name='Arial'):
    run.font.name = font_name
    run.font.size = Pt(size)
    run.font.bold = bold
    run.font.italic = italic
    if color:
        run.font.color.rgb = RGBColor(*color)
    rPr = run._r.get_or_add_rPr()
    rtl = OxmlElement('w:rtl')
    rPr.append(rtl)
    rFonts = rPr.find(qn('w:rFonts'))
    if rFonts is None:
        rFonts = OxmlElement('w:rFonts')
        rPr.append(rFonts)
    rFonts.set(qn('w:cs'), font_name)
    rFonts.set(qn('w:ascii'), font_name)
    rFonts.set(qn('w:hAnsi'), font_name)


def p_he(text='', size=12, bold=False, italic=False, align=WD_ALIGN_PARAGRAPH.RIGHT,
         line_spacing=1.15, space_after=6, style=None, color=None):
    par = doc.add_paragraph(style=style)
    par.alignment = align
    pf = par.paragraph_format
    pf.line_spacing = line_spacing
    pf.space_after = Pt(space_after)
    set_rtl(par)
    if text:
        run = par.add_run(text)
        style_run(run, size=size, bold=bold, italic=italic, color=color)
    return par


def h_he(text, level=1):
    h = doc.add_heading('', level=level)
    h.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    set_rtl(h)
    size = {1: 18, 2: 14, 3: 12}.get(level, 12)
    run = h.add_run(text)
    style_run(run, size=size, bold=True, color=(0, 0, 0))
    return h


def page_break():
    par = doc.add_paragraph()
    run = par.add_run()
    run.add_break(WD_BREAK.PAGE)


FIG_COUNTER = [0]
TAB_COUNTER = [0]


def add_field(paragraph, instr_text):
    run = paragraph.add_run()
    fld1 = OxmlElement('w:fldChar')
    fld1.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.set(qn('xml:space'), 'preserve')
    instr.text = instr_text
    r_el = run._r
    r_el.append(fld1)
    r_el.append(instr)


def end_field(paragraph, fallback_text):
    run = paragraph.add_run()
    fld_sep = OxmlElement('w:fldChar')
    fld_sep.set(qn('w:fldCharType'), 'separate')
    t = OxmlElement('w:t')
    t.text = fallback_text
    r_el = run._r
    r_el.append(fld_sep)
    r_el.append(t)
    run2 = paragraph.add_run()
    fld_end = OxmlElement('w:fldChar')
    fld_end.set(qn('w:fldCharType'), 'end')
    run2._r.append(fld_end)


def add_seq_field(paragraph, seq_name, fallback_num, size=11, bold=True):
    run = paragraph.add_run()
    fld1 = OxmlElement('w:fldChar')
    fld1.set(qn('w:fldCharType'), 'begin')
    instr = OxmlElement('w:instrText')
    instr.set(qn('xml:space'), 'preserve')
    instr.text = f' SEQ {seq_name} \\* ARABIC '
    r_el = run._r
    r_el.append(fld1)
    r_el.append(instr)
    style_run(run, size=size, bold=bold)

    run_sep = paragraph.add_run()
    fld_sep = OxmlElement('w:fldChar')
    fld_sep.set(qn('w:fldCharType'), 'separate')
    run_sep._r.append(fld_sep)
    style_run(run_sep, size=size, bold=bold)

    run_val = paragraph.add_run(str(fallback_num))
    style_run(run_val, size=size, bold=bold)

    run_end = paragraph.add_run()
    fld_end = OxmlElement('w:fldChar')
    fld_end.set(qn('w:fldCharType'), 'end')
    run_end._r.append(fld_end)
    style_run(run_end, size=size, bold=bold)


def add_figure(filename, caption_he):
    FIG_COUNTER[0] += 1
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(os.path.join(FIG_DIR, filename), width=Cm(15))
    cap = p_he(align=WD_ALIGN_PARAGRAPH.CENTER, size=11, space_after=10)
    run = cap.add_run('תרשים ')
    style_run(run, size=11, bold=True)
    add_seq_field(cap, 'Figure', FIG_COUNTER[0], size=11, bold=True)
    run2 = cap.add_run(f': {caption_he}')
    style_run(run2, size=11)
    return FIG_COUNTER[0]


def add_table(headers, rows, caption_he):
    TAB_COUNTER[0] += 1
    cap = p_he(align=WD_ALIGN_PARAGRAPH.RIGHT, size=11, space_after=4)
    run = cap.add_run('טבלה ')
    style_run(run, size=11, bold=True)
    add_seq_field(cap, 'Table', TAB_COUNTER[0], size=11, bold=True)
    run2 = cap.add_run(f': {caption_he}')
    style_run(run2, size=11)

    table = doc.add_table(rows=1, cols=len(headers))
    table.style = 'Light Grid Accent 1'
    table.alignment = WD_ALIGN_PARAGRAPH.CENTER
    tblPr = table._tbl.tblPr
    bidiVisual = OxmlElement('w:bidiVisual')
    tblPr.append(bidiVisual)

    hdr_cells = table.rows[0].cells
    for i, htext in enumerate(headers):
        cell = hdr_cells[i]
        para = cell.paragraphs[0]
        para.alignment = WD_ALIGN_PARAGRAPH.CENTER
        set_rtl(para)
        run = para.add_run(htext)
        style_run(run, size=11, bold=True)

    for row in rows:
        cells = table.add_row().cells
        for i, val in enumerate(row):
            para = cells[i].paragraphs[0]
            para.alignment = WD_ALIGN_PARAGRAPH.CENTER
            set_rtl(para)
            run = para.add_run(str(val))
            style_run(run, size=11)
    doc.add_paragraph()
    return TAB_COUNTER[0]


